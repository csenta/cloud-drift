"""
Unified Command-Line Interface for CloudDrift.
"""

import argparse
import json
import os
import sys

from cloud_drift.core.models import CloudDriftReport
from cloud_drift.core.state_parser import StateParser
from cloud_drift.engines.compliance import ComplianceEngine
from cloud_drift.engines.drift_detector import DriftDetector
from cloud_drift.engines.remediation import RemediationSynthesizer
from cloud_drift.reporters.cli_reporter import CLIReporter
from cloud_drift.reporters.html_reporter import HTMLReporter


def compute_risk_score(findings) -> int:
    score = 0
    weights = {"CRITICAL": 25, "HIGH": 15, "MEDIUM": 8, "LOW": 3}
    for f in findings:
        score += weights.get(f.severity, 5)
    return min(100, score)


def run_drift_analysis(declared_file: str, live_file: str) -> CloudDriftReport:
    declared = StateParser.parse_declared_state(declared_file)
    live = StateParser.parse_live_state(live_file)

    # 1. Structural IaC drift & unmanaged resources
    drift_findings = DriftDetector.detect_drift(declared, live)

    # 2. Out-of-band security compliance degradations
    compliance_findings = ComplianceEngine.audit_security_degradations(declared, live)

    all_findings = drift_findings + compliance_findings

    # 3. Synthesize GitOps HCL patches & terraform import scripts
    remediations = RemediationSynthesizer.synthesize_remediations(all_findings, live)

    risk_score = compute_risk_score(all_findings)

    return CloudDriftReport(
        declared_path=declared_file,
        live_path=live_file,
        declared_count=len(declared),
        live_count=len(live),
        findings=all_findings,
        remediations=remediations,
        risk_score=risk_score,
    )


def handle_diff(args: argparse.Namespace) -> int:
    try:
        report = run_drift_analysis(args.declared, args.live)
    except Exception as e:
        print(f"[ERROR] Drift analysis failed: {e}")
        return 1

    # 1. Terminal summary
    CLIReporter.print_summary(report)

    # 2. JSON export
    if args.output_json:
        with open(args.output_json, "w", encoding="utf-8") as f:
            json.dump(report.to_dict(), f, indent=2)
        print(f"📄 JSON report saved to {args.output_json}")

    # 3. HTML export
    if args.output_html:
        html = HTMLReporter.generate(report)
        with open(args.output_html, "w", encoding="utf-8") as f:
            f.write(html)
        print(f"📊 Interactive HTML report saved to {args.output_html}")

    # 4. CI quality gate
    if args.fail_on_severity:
        threshold = args.fail_on_severity.upper()
        severity_order = {"LOW": 1, "MEDIUM": 2, "HIGH": 3, "CRITICAL": 4}
        thresh_val = severity_order.get(threshold, 3)

        violates = any(severity_order.get(f.severity, 0) >= thresh_val for f in report.findings)
        if violates:
            print(f"❌ CI Gate Failed: Found drift matching or exceeding severity '{threshold}'!")
            return 2

    return 0


def handle_import(args: argparse.Namespace) -> int:
    try:
        report = run_drift_analysis(args.declared, args.live)
    except Exception as e:
        print(f"[ERROR] Import analysis failed: {e}")
        return 1

    import_actions = [r for r in report.remediations if r.action_type == "TERRAFORM_IMPORT"]

    if not import_actions:
        print("✅ No unmanaged resources found requiring import.")
        return 0

    script_lines = [
        "#!/usr/bin/env bash",
        "# Generated by CloudDrift: Terraform Import Script for Unmanaged Resources",
        "set -euo pipefail",
        "",
    ]
    for act in import_actions:
        script_lines.append(f"echo '==> Importing {act.resource_type}.{act.resource_name}...'")
        script_lines.append(act.command)

    script_content = "\n".join(script_lines) + "\n"

    if args.output:
        with open(args.output, "w", encoding="utf-8") as f:
            f.write(script_content)
        os.chmod(args.output, 0o755)
        print(f"✅ Generated import script written to {args.output} ({len(import_actions)} resources)")
    else:
        print(script_content)

    return 0


def handle_remediate(args: argparse.Namespace) -> int:
    try:
        report = run_drift_analysis(args.declared, args.live)
    except Exception as e:
        print(f"[ERROR] Remediation generation failed: {e}")
        return 1

    hcl_patches = [r.patch_content for r in report.remediations if r.patch_content]

    if not hcl_patches:
        print("✅ No security remediations required.")
        return 0

    combined_hcl = "\n\n".join(hcl_patches) + "\n"

    if args.output_hcl:
        with open(args.output_hcl, "w", encoding="utf-8") as f:
            f.write(combined_hcl)
        print(f"✅ Hardened HCL patches written to {args.output_hcl}")
    else:
        print("\n🔧 Hardened GitOps HCL Patches:")
        print(combined_hcl)

    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        prog="cloud-drift",
        description="CloudDrift: Autonomous Multi-Cloud IaC Drift & Security Compliance Remediator for Terraform/OpenTofu",
    )
    subparsers = parser.add_subparsers(dest="command", help="Sub-commands")

    # diff
    p_diff = subparsers.add_parser("diff", help="Analyze drift and security compliance between declared and live cloud")
    p_diff.add_argument("--declared", "-d", required=True, help="Path to declared terraform.tfstate or state JSON")
    p_diff.add_argument("--live", "-l", required=True, help="Path to live cloud inventory snapshot JSON")
    p_diff.add_argument("--output-json", default="", help="Path to write JSON report")
    p_diff.add_argument("--output-html", default="", help="Path to write interactive HTML dashboard")
    p_diff.add_argument(
        "--fail-on-severity",
        choices=["LOW", "MEDIUM", "HIGH", "CRITICAL"],
        default=None,
        help="Exit code 2 if drift >= severity threshold",
    )

    # import
    p_import = subparsers.add_parser("import", help="Generate automated terraform import script for unmanaged resources")
    p_import.add_argument("--declared", "-d", required=True, help="Path to declared state file")
    p_import.add_argument("--live", "-l", required=True, help="Path to live cloud snapshot file")
    p_import.add_argument("--output", "-o", default="import_unmanaged.sh", help="Output shell script filename")

    # remediate
    p_remedy = subparsers.add_parser("remediate", help="Synthesize GitOps HCL patches for drifted security settings")
    p_remedy.add_argument("--declared", "-d", required=True, help="Path to declared state file")
    p_remedy.add_argument("--live", "-l", required=True, help="Path to live cloud snapshot file")
    p_remedy.add_argument("--output-hcl", default="", help="Path to write hardened .tf file")

    args = parser.parse_args()

    if not args.command:
        parser.print_help()
        return 0

    if args.command == "diff":
        return handle_diff(args)
    elif args.command == "import":
        return handle_import(args)
    elif args.command == "remediate":
        return handle_remediate(args)

    return 0


if __name__ == "__main__":
    sys.exit(main())
